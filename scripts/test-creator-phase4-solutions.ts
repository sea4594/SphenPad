import type { CellRC, PuzzleDefinition } from "../src/core/model";
import { createAuthoredPuzzleDefinition } from "../src/sudokupad/creator/nativeAuthoring";
import { compareCreatorSolutions, findCreatorSolutions } from "../src/sudokupad/creator/solver";

const check = (test: unknown, message: string) => { if (!test) throw new Error(message); };
const rc = (r: number, c: number): CellRC => ({ r, c });
const base = (): PuzzleDefinition => createAuthoredPuzzleDefinition({ id: "phase4", rows: 4, cols: 4, subgrid: { r: 2, c: 2 }, digitRange: { min: 1, max: 4 }, meta: {} });
const solved = [[1, 2, 3, 4], [3, 4, 1, 2], [2, 1, 4, 3], [4, 3, 2, 1]];
const almost = (): PuzzleDefinition => ({ ...base(), givens: solved.flatMap((row, r) => row.flatMap((value, c) => r === 3 && c === 2 ? [] : [{ rc: rc(r, c), v: String(value) }])) });

let report = findCreatorSolutions(base(), { searchMode: "first", maxNodes: 10_000 });
check(report.status === "found" && !report.exact && report.solutionsFound === 1 && report.solutions.length === 1, "find one must not assert uniqueness");
report = findCreatorSolutions(base(), { searchMode: "unique", maxNodes: 10_000 });
check(report.status === "multiple" && !report.exact && report.solutionsFound === 2, "two examples disprove uniqueness without an exact total");
check(report.solutions.length === 2, "two example solutions should be retained");
const differences = compareCreatorSolutions(report.solutions[0], report.solutions[1]);
check(differences.length > 0 && differences.every((diff) => diff.first !== diff.second), "different solutions must identify different cells");
const before = JSON.stringify(base());
const progress: number[] = [];
report = findCreatorSolutions(base(), { searchMode: "count", maxSolutions: 1000, maxNodes: 10_000 }, { onProgress: ({ nodes }) => progress.push(nodes) });
check(report.status === "multiple" && report.exact && report.solutionsFound === 288, "4x4 Sudoku has exactly 288 solutions");
check(report.solutions.length === 2, "counting must not retain every solution in memory");
check(progress.length > 0 && progress.every((value, i) => i === 0 || value > progress[i - 1]), "progress must advance monotonically");
check(before === JSON.stringify(base()), "search must not mutate the puzzle definition");
report = findCreatorSolutions(base(), { searchMode: "count", maxSolutions: 17, maxNodes: 10_000 });
check(report.status === "multiple" && !report.exact && report.solutionsFound === 17 && report.stopReason === "solutions", "solution cap must produce a lower bound");
report = findCreatorSolutions(base(), { searchMode: "count", maxSolutions: 1000, maxNodes: 30 });
check(!report.exact && report.stopReason === "nodes", "node cap must not be reported as exact");
report = findCreatorSolutions(almost(), { searchMode: "count", maxSolutions: 1000 });
check(report.status === "solved" && report.exact && report.solutionsFound === 1, "uniqueness must be proven after exhaustive search");
report = findCreatorSolutions(almost(), { searchMode: "first", maxNodes: 500 });
check(report.status === "solved" && report.exact && report.solutionsFound === 1, "exhaustive find one may legitimately prove uniqueness");
report = findCreatorSolutions(almost(), { searchMode: "unique", maxSolutions: 1 });
check(report.exact && report.status === "solved", "a cap reached on the last branch may still prove uniqueness");
report = findCreatorSolutions(base(), { searchMode: "count", maxSolutions: 1 });
check(!report.exact && report.solutionsFound === 1 && report.status === "limit", "a one-solution count cap is not a proof");
const impossible: PuzzleDefinition = { ...base(), givens: [{ rc: rc(0, 0), v: "1" }, { rc: rc(0, 1), v: "2" }, { rc: rc(0, 2), v: "3" }, { rc: rc(1, 3), v: "4" }] };
report = findCreatorSolutions(impossible, { searchMode: "count", maxNodes: 10_000 });
check(report.status === "none" && report.exact && report.solutionsFound === 0, "no solution is proven only by exhaustive search");
check(compareCreatorSolutions(report.solutions[0] ?? [], []).length === 0, "empty comparison is safe");
console.log("creator Phase 4 search/count/compare tests passed");
